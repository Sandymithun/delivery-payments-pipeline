-- ============================================================================
-- One-off Snowflake setup for the delivery-payments pipeline.
-- Run as ACCOUNTADMIN (free trial accounts have it). Replace the <...> values.
-- ============================================================================

USE ROLE ACCOUNTADMIN;

-- ---------------------------------------------------------------- compute + db
CREATE WAREHOUSE IF NOT EXISTS TRANSFORMING
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS DELIVERY;
CREATE SCHEMA IF NOT EXISTS DELIVERY.RAW;        -- landed data, loaded by Python/COPY
CREATE SCHEMA IF NOT EXISTS DELIVERY.ANALYTICS;  -- dbt builds here (+ _staging, _snapshots)

-- ---------------------------------------------------------------- role + user
CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT USAGE ON WAREHOUSE TRANSFORMING TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE DELIVERY TO ROLE TRANSFORMER;
GRANT ALL ON SCHEMA DELIVERY.RAW TO ROLE TRANSFORMER;
GRANT ALL ON SCHEMA DELIVERY.ANALYTICS TO ROLE TRANSFORMER;

CREATE USER IF NOT EXISTS PIPELINE_USER
  PASSWORD = '<choose-a-strong-password>'
  DEFAULT_ROLE = TRANSFORMER DEFAULT_WAREHOUSE = TRANSFORMING
  MUST_CHANGE_PASSWORD = FALSE;
GRANT ROLE TRANSFORMER TO USER PIPELINE_USER;

-- ---------------------------------------------------------------- external stage
-- Option A: AWS S3 via a storage integration (recommended, no keys in Snowflake)
CREATE STORAGE INTEGRATION IF NOT EXISTS S3_LAKE_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<aws-account-id>:role/snowflake-delivery-lake'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<your-bucket>/raw/');
-- DESC INTEGRATION S3_LAKE_INT;  -> copy STORAGE_AWS_IAM_USER_ARN + EXTERNAL_ID into the IAM role trust policy
GRANT USAGE ON INTEGRATION S3_LAKE_INT TO ROLE TRANSFORMER;

