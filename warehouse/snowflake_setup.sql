USE ROLE TRANSFORMER;
USE WAREHOUSE TRANSFORMING;
USE SCHEMA DELIVERY.RAW;

CREATE FILE FORMAT IF NOT EXISTS CSV_FORMAT
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE TRIM_SPACE = FALSE;

-- stage root = bucket root, the loader appends raw/<entity>/dt=<date>/
CREATE STAGE IF NOT EXISTS LAKE_STAGE
  URL = 's3://<your-bucket>/'
  STORAGE_INTEGRATION = S3_LAKE_INT
  FILE_FORMAT = CSV_FORMAT;

-- ---------------------------------------------------------------- raw tables
-- Everything VARCHAR: raw keeps exactly what the source sent; dbt staging casts.
CREATE TABLE IF NOT EXISTS CUSTOMERS (
  CUSTOMER_ID VARCHAR, FIRST_NAME VARCHAR, LAST_NAME VARCHAR, EMAIL VARCHAR,
  CITY VARCHAR, SIGNUP_DATE VARCHAR,
  _BATCH_DATE DATE, _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_NTZ);

CREATE TABLE IF NOT EXISTS MERCHANTS (
  MERCHANT_ID VARCHAR, MERCHANT_NAME VARCHAR, CATEGORY VARCHAR, CITY VARCHAR,
  COMMISSION_RATE VARCHAR, ONBOARDED_DATE VARCHAR, UPDATED_AT VARCHAR,
  _BATCH_DATE DATE, _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_NTZ);

CREATE TABLE IF NOT EXISTS ORDERS (
  ORDER_ID VARCHAR, CUSTOMER_ID VARCHAR, MERCHANT_ID VARCHAR, ORDER_TS VARCHAR,
  STATUS VARCHAR, ITEMS_COUNT VARCHAR, SUBTOTAL VARCHAR, DELIVERY_FEE VARCHAR,
  TIP VARCHAR, TOTAL_AMOUNT VARCHAR, CURRENCY VARCHAR, DELIVERY_MINUTES VARCHAR,
  _BATCH_DATE DATE, _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_NTZ);

CREATE TABLE IF NOT EXISTS PAYMENTS (
  PAYMENT_ID VARCHAR, ORDER_ID VARCHAR, PAYMENT_TS VARCHAR, METHOD VARCHAR,
  AMOUNT VARCHAR, CURRENCY VARCHAR, STATUS VARCHAR,
  _BATCH_DATE DATE, _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_NTZ);

